import { test } from 'node:test';
import * as assert from 'node:assert/strict';
import {
  catalogScarpProjects, projectEntryPath, type ScarpProjectCandidate
} from '../src/editorProjectCatalog';

const v2 = (name: string, entry = 'src/main.srp') =>
  'project "' + name + '" {\n' +
  '  version: "0.1.0"\n' +
  '  entry: "' + entry + '"\n' +
  '  type: "application"\n' +
  '  dependencies {}\n}\n';
const legacy = (name: string, entry = 'src/main.srp') =>
  'scarp-project: 1\nname: ' + name + '\nentry: ' + entry + '\n';
const candidate = (filename: string, content: string): ScarpProjectCandidate => ({
  filename, content
});
test('empty project list is safe and deterministic', () => {
  assert.deepEqual(catalogScarpProjects([]), { projects: [], issues: [] });
});
test('published v2 scaffold exposes name, version and relative entry', () => {
  const result = catalogScarpProjects([candidate('scarp.project', v2('example'))]);
  assert.deepEqual(result.issues, []);
  assert.deepEqual(result.projects, [{
    name: 'example', version: '0.1.0',
    entry: 'src/main.srp', root: '', manifest: 'scarp.project',
    kind: 'declarative-v2'
  }]);
  assert.equal(projectEntryPath(result.projects[0]), 'src/main.srp');
});
test('legacy scaffold remains distinct from v2', () => {
  const result = catalogScarpProjects([candidate('Scarp.project', legacy('old'))]);
  assert.equal(result.issues.length, 0);
  assert.equal(result.projects[0].kind, 'legacy-v1');
  assert.equal(result.projects[0].version, undefined);
});
test('nested subprojects remain independent across deep workspace trees', () => {
  const result = catalogScarpProjects([
    candidate('Scarp-Practice/basic_tuple/scarp.project', v2('tuple-practice')),
    candidate('Scarp-Practice/basic_integer/scarp.project', v2('integer-practice')),
    candidate('another/legacy/Scarp.project', legacy('legacy'))
  ]);
  assert.equal(result.projects.length, 3);
  assert.deepEqual(result.projects.map(x => x.root), [
    'another/legacy',
    'Scarp-Practice/basic_integer',
    'Scarp-Practice/basic_tuple'
  ]);
  assert.equal(projectEntryPath(result.projects[2]),
    'Scarp-Practice/basic_tuple/src/main.srp');
});
test('v2 fields accept reordering and full-line comments', () => {
  const content = [
    '// generated by Scarp',
    'project "application" {',
    'type: "application"',
    '// no dependencies',
    'entry: "src/main.srp"',
    'dependencies {}',
    'version: "1.2.3-alpha.1"',
    '}'
  ].join('\n');
  const result = catalogScarpProjects([candidate('sub/scarp.project', content)]);
  assert.equal(result.issues.length, 0);
  assert.equal(result.projects[0].version, '1.2.3-alpha.1');
});
test('invalid v2 braces, type or missing required fields are refused', () => {
  const bad = [
    v2('valid').replace('project "valid"', 'component "valid"'),
    v2('valid').replace('type: "application"', 'type: "library"'),
    v2('valid').replace('version: "0.1.0"', ''),
    v2('valid').replace('entry: "src/main.srp"', ''),
    v2('valid').replace('dependencies {}', 'dependencies { "repo" }'),
    v2('valid').replace('version: "0.1.0"', 'version: "invalid"'),
    v2('valid').replace('}', ''),
    v2('valid').replace('entry: "src/main.srp"',
      'entry: "src/main.srp"\nentry: "src/extra.srp"')
  ];
  for (const content of bad) {
    const result = catalogScarpProjects([candidate('scarp.project', content)]);
    assert.deepEqual(result.projects, [], content);
    assert.equal(result.issues[0].kind, 'unrecognized');
  }
});
test('project entries cannot traverse or escape workspace paths', () => {
  for (const entry of [
    '../outside.srp', './main.srp', 'src/../main.srp', '/absolute.srp',
    'C:/drive.srp', 'src\\wrong.srp', 'src//main.srp',
    'main.txt', 'file%2esrp'
  ]) {
    const result = catalogScarpProjects([
      candidate('nested/scarp.project', v2('safe', entry))
    ]);
    assert.equal(result.projects.length, 0, entry);
  }
});
test('escaped project names are not evaluated or decoded', () => {
  for (const content of [
    v2('hello\\"bad'),
    v2('name').replace('"name"', '"bad\\\\escape"')
  ]) {
    assert.equal(catalogScarpProjects([
      candidate('scarp.project', content)
    ]).projects.length, 0);
  }
});
test('legacy format needs an identifier and safe source entry', () => {
  for (const content of [
    legacy('bad name'), legacy('good').replace('scarp-project: 1', 'scarp-project: 2'),
    legacy('good').replace('entry: src/main.srp', 'entry: ../escape.srp'),
    legacy('good').replace('name: good', 'name: good\nname: duplicate'),
    legacy('good').replace('entry: src/main.srp', '')
  ]) {
    const result = catalogScarpProjects([candidate('Scarp.project', content)]);
    assert.equal(result.projects.length, 0);
    assert.equal(result.issues[0].kind, 'unrecognized');
  }
});
test('malicious manifest filenames are rejected independently of text', () => {
  for (const filename of [
    '../scarp.project', '/root/scarp.project', 'src/../../scarp.project',
    './scarp.project', 'folder\\scarp.project', 'not-a-manifest.txt'
  ]) {
    const result = catalogScarpProjects([candidate(filename, v2('good'))]);
    assert.equal(result.projects.length, 0, filename);
    assert.equal(result.issues[0].kind, 'unsafe-path');
  }
});
test('duplicate manifests in same directory cannot create conflicting projects', () => {
  const result = catalogScarpProjects([
    candidate('project/Scarp.project', legacy('old')),
    candidate('project/scarp.project', v2('new'))
  ]);
  assert.equal(result.projects.length, 1);
  assert.equal(result.issues[0].kind, 'duplicate');
});
test('catalog respects manifest count and UTF-8 byte budgets', () => {
  const result = catalogScarpProjects([
    candidate('a/scarp.project', v2('a')), candidate('b/scarp.project', v2('b'))
  ], { maxManifests: 1 });
  assert.equal(result.projects.length, 1);
  assert.equal(result.issues[0].kind, 'limit');
  const tooLong = catalogScarpProjects([candidate('scarp.project', v2('😀'))],
    { maxManifestBytes: 12 });
  assert.deepEqual(tooLong.projects, []);
  assert.equal(tooLong.issues[0].kind, 'oversized');
});
test('zero or fractional limits fail closed', () => {
  for (const value of [0, -1, 1.5, NaN, Infinity]) {
    const result = catalogScarpProjects([candidate('scarp.project', v2('x'))],
      { maxManifests: value });
    assert.equal(result.projects.length, 0);
    assert.equal(result.issues[0].kind, 'limit');
  }
});
test('catalog output is independent of input ordering', () => {
  const first = [
    candidate('z/scarp.project', v2('z')),
    candidate('a/scarp.project', v2('a')),
    candidate('m/Scarp.project', legacy('m'))
  ];
  assert.deepEqual(catalogScarpProjects(first),
    catalogScarpProjects([...first].reverse()));
});
test('entry path helpers reject mutated unsafe entries and parent folders', () => {
  const project = catalogScarpProjects([candidate('scarp.project', v2('ok'))]).projects[0];
  assert.equal(projectEntryPath({ ...project, entry: '../bad.srp' }), undefined);
  assert.equal(projectEntryPath({ ...project, root: '../bad' }), undefined);
});
